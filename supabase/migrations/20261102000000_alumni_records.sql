-- =====================================================
--  GLUK YEARBOOK 2026 — THE ALUMNI REGISTRATION FORM
--
--    alumni_records   one per account: the Directorate of External Affairs' alumni registration form, filled in
--                     online (alumni-form.html) and signed by the student (typed full name + the declaration ticked).
--                     Private: only the api reads or writes it, for the student who sent it, admins with the alumni
--                     permission (office.html) and the super admin. Nothing from it is on a public page.
--
--  profile_id has no foreign key on purpose: deleting a yearbook profile (and its 90-day purge) leaves the alumni
--  record, which the student consented to separately. They ask the office to remove it (withdraw_requested_at).
--  Undo: supabase/rollback/20261102000000_alumni_records_down.sql. Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.alumni_records (
  id                     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid                    text        NOT NULL UNIQUE,
  profile_id             bigint,
  -- Section A: personal details
  full_name              text        NOT NULL,
  reg                    text        NOT NULL,
  national_id            text        NOT NULL,
  gender                 text        NOT NULL,
  dob                    date        NOT NULL,
  phone                  text        NOT NULL,
  email                  text        NOT NULL,
  postal_address         text,
  residence              text        NOT NULL,       -- county (in Kenya) or country of residence
  -- Section B: academic details
  school                 text        NOT NULL,
  programme              text        NOT NULL,
  specialization         text,
  admission_intake       text        NOT NULL,       -- January, May or September
  admission_year         int         NOT NULL,
  graduation_year        int         NOT NULL,
  study_mode             text        NOT NULL,
  -- Section C: employment / current engagement
  employment_status      text        NOT NULL,
  employer               text,
  job_title              text,
  work_location          text,
  further_studies        text,
  -- Section D: alumni engagement preferences
  interests              text[]      NOT NULL DEFAULT '{}',
  interest_other         text,
  -- the declaration
  signature_name         text        NOT NULL,
  signed_at              timestamptz NOT NULL,
  submitted_at           timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  withdraw_requested_at  timestamptz,
  withdraw_reason        text
);
CREATE INDEX IF NOT EXISTS alumni_records_year_idx ON public.alumni_records (graduation_year);

ALTER TABLE public.alumni_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.alumni_records FROM anon, authenticated;

COMMIT;

-- =====================================================
--  GLUK YEARBOOK 2026 — FRIENDS + WHAT'S NEW
--
--    friend_links       a friend request (pending) or a friendship (accepted), one per pair of people
--    friend_events      what a person did that their friends hear about: new photos, a profile update
--                       (written by the api when a profile changes; kept for the Alerts tab)
--    announcements      "What's new" posts from the admin: app updates and why they are exciting
--    announcements_public   the visible ones, for everyone
--
--  Friendships are private: nobody but the api function reads or writes friend_links or friend_events.
--  Undo: supabase/rollback/20261027000000_friends_and_news_down.sql. Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.friend_links (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_uid      text        NOT NULL,
  to_uid        text        NOT NULL CHECK (to_uid <> from_uid),
  from_profile  bigint      NOT NULL,
  to_profile    bigint      NOT NULL,
  status        text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  accepted_at   timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS friend_links_pair ON public.friend_links (LEAST(from_uid, to_uid), GREATEST(from_uid, to_uid));
CREATE INDEX IF NOT EXISTS friend_links_from_idx ON public.friend_links (from_uid);
CREATE INDEX IF NOT EXISTS friend_links_to_idx ON public.friend_links (to_uid);

CREATE TABLE IF NOT EXISTS public.friend_events (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid         text        NOT NULL,
  profile_id  bigint      NOT NULL,
  kind        text        NOT NULL CHECK (kind IN ('photo', 'update')),
  n           integer     NOT NULL DEFAULT 1,
  detail      text        CHECK (char_length(detail) <= 120),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS friend_events_uid_idx ON public.friend_events (uid, created_at DESC);

CREATE TABLE IF NOT EXISTS public.announcements (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emoji       text        NOT NULL DEFAULT '✨' CHECK (char_length(emoji) <= 16),
  title       text        NOT NULL CHECK (char_length(title) BETWEEN 3 AND 120),
  body        text        NOT NULL DEFAULT '' CHECK (char_length(body) <= 600),
  url         text        CHECK (char_length(url) <= 300),
  hidden      boolean     NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.friend_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.friend_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.friend_links, public.friend_events, public.announcements FROM anon, authenticated;

CREATE OR REPLACE VIEW public.announcements_public WITH (security_invoker = false) AS
  SELECT id, emoji, title, body, url, created_at FROM public.announcements WHERE NOT hidden;
REVOKE ALL ON public.announcements_public FROM anon, authenticated;
GRANT SELECT ON public.announcements_public TO anon, authenticated;

COMMIT;

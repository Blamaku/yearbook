--  GLUK YEARBOOK 2026 — ADMINS AND WHAT EACH MAY DO
--
--    admins   one row per admin email, with the permissions the super admin ticked for them in People › Admins
--             (the list of permissions and what each allows is in supabase-api/index.ts, CONFIG.perms). Office
--             dashboards are permissions too: dos.students and dos.clubs (Dean of Students), alumni (External Affairs).
--             The super admin (the adminEmail account) is not in it: that account may do everything.
--
--  Everyone in office_admins keeps their office (it is copied in once; office_admins is no longer read).
--  Only the api function reads or writes it. Undo: supabase/rollback/20261101000000_admin_perms_down.sql.
--  Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.admins (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text        NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%_@_%.__%'),
  note        text        CHECK (note IS NULL OR char_length(note) <= 80),       -- who they are, e.g. "Dean of Students"
  perms       text[]      NOT NULL DEFAULT '{}',
  granted_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.admins (email, perms, granted_by, created_at, updated_at)
SELECT o.email, array_agg(DISTINCT p ORDER BY p), min(o.granted_by), min(o.created_at), now()
FROM public.office_admins o
CROSS JOIN LATERAL unnest(CASE o.office WHEN 'dos' THEN ARRAY['dos.students', 'dos.clubs'] ELSE ARRAY['alumni'] END) AS p
GROUP BY o.email
ON CONFLICT (email) DO NOTHING;

ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admins FROM anon, authenticated;

COMMIT;

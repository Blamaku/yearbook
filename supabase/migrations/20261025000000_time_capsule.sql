-- =====================================================
--  GLUK YEARBOOK 2026 — TIME CAPSULE (capsule.html)
--
--    grad_days    each class's graduation day, posted by the admin (00:00 in Kisumu that day)
--    capsules     notes (and a photo) a student writes to their future self; sealed until their
--                 own class's graduation day is posted and has come. Only the writer ever reads them.
--    grad_days_public   the posted days, for everyone (no logins)
--
--  Nobody but the api function reads or writes the tables.
--  Undo: supabase/rollback/20261025000000_time_capsule_down.sql. Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.grad_days (
  classyear  text        PRIMARY KEY CHECK (classyear ~ '^[0-9]{4}$'),
  opens_at   timestamptz NOT NULL,
  posted_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.capsules (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid         text        NOT NULL,
  body        text        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  photo_url   text        CHECK (char_length(photo_url) <= 600),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS capsules_uid_idx ON public.capsules (uid, created_at);

ALTER TABLE public.grad_days ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.capsules ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.grad_days, public.capsules FROM anon, authenticated;

CREATE OR REPLACE VIEW public.grad_days_public WITH (security_invoker = false) AS
  SELECT classyear, opens_at FROM public.grad_days;
REVOKE ALL ON public.grad_days_public FROM anon, authenticated;
GRANT SELECT ON public.grad_days_public TO anon, authenticated;

-- The Class of 2026 graduates on Saturday 21 November 2026
INSERT INTO public.grad_days (classyear, opens_at) VALUES ('2026', timestamptz '2026-11-20 21:00:00+00') ON CONFLICT (classyear) DO NOTHING;

COMMIT;

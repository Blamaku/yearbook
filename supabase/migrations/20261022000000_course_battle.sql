-- =====================================================
--  GLUK YEARBOOK 2026 — COURSE BATTLE ("Think it's easy?", challenge.html)
--
--    chal_runs    each signed-in round, timed by the api (like Who's who?'s kyu_runs)
--    chal_best    each player's best round per quiz, with the team their course belongs to
--    chal_board   per team: players, average best score and perfect rounds, counting only each player's
--                 own profession's quiz. Totals only: no names, no logins. Everyone may read it.
--
--  Only players with a yearbook profile count. Nobody but the api function reads or writes the tables.
--  Order: 1) this file  2) redeploy supabase-api/index.ts  3) deploy the website
--  Undo:  supabase/rollback/20261022000000_course_battle_down.sql
--  Safe to run more than once.
-- =====================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.chal_runs (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid         text        NOT NULL,
  quiz        text        NOT NULL CHECK (char_length(quiz) <= 20),
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  score       integer     CHECK (score BETWEEN 0 AND 10),
  seconds     integer
);
CREATE INDEX IF NOT EXISTS chal_runs_uid_idx ON public.chal_runs (uid, started_at DESC);

CREATE TABLE IF NOT EXISTS public.chal_best (
  uid         text        NOT NULL,
  quiz        text        NOT NULL CHECK (char_length(quiz) <= 20),
  profile_id  bigint      NOT NULL,
  team        text        CHECK (char_length(team) <= 20),     -- the quiz of the player's own course (NULL: no matching course)
  score       integer     NOT NULL CHECK (score BETWEEN 0 AND 10),
  seconds     integer     NOT NULL,
  plays       integer     NOT NULL DEFAULT 1,
  achieved_at timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (uid, quiz)
);
CREATE INDEX IF NOT EXISTS chal_best_team_idx ON public.chal_best (team, quiz);

ALTER TABLE public.chal_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chal_best ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.chal_runs, public.chal_best FROM anon, authenticated;

-- The board: one line per team, from each player's best round on their own profession's quiz
CREATE OR REPLACE VIEW public.chal_board WITH (security_invoker = false) AS
  SELECT team,
         count(*)::int                                   AS players,
         round(avg(score)::numeric, 1)                   AS avg_score,
         (count(*) FILTER (WHERE score = 10))::int       AS perfect,
         max(updated_at)                                 AS last_play
  FROM public.chal_best
  WHERE team IS NOT NULL AND quiz = team
  GROUP BY team;
REVOKE ALL ON public.chal_board FROM anon, authenticated;
GRANT SELECT ON public.chal_board TO anon, authenticated;
COMMENT ON VIEW public.chal_board IS 'Course battle totals for challenge.html: per team, no names or logins.';

COMMIT;

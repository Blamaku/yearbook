-- =====================================================
--  GLUK YEARBOOK 2026 — THE CLASS WALL (wall.html): graduation week days 3–6
--
--    grad_posts        what students add before graduation week, each sealed until its own day:
--                        memory  (Time Machine, Tue 17 Nov)   a memory from one year, 2022–2026
--                        tag     (My People, Wed 18 Nov)      "my best friend / study partner / mentor / chaos partner is …"
--                        song    (Soundtrack, Thu 19 Nov)     a song for the class playlist
--                        joke    (Inside Jokes, Thu 19 Nov)   something only the Class of 2026 understands
--                        advice  (Pass the Torch, Fri 20 Nov) one piece of advice for the freshers
--    grad_posts_wall   the public wall: each kind only from its day; names come live from the profiles
--    grad_posts_count  how many of each kind are sealed so far (numbers only)
--
--  Every day opens at 00:00 in Kisumu. Nobody but the api function reads or writes the table.
--  Undo: supabase/rollback/20261026000000_class_wall_down.sql. Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.grad_posts (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid             text        NOT NULL,
  profile_id      bigint      NOT NULL,                          -- who added it
  kind            text        NOT NULL CHECK (kind IN ('memory', 'tag', 'song', 'joke', 'advice')),
  year            integer     CHECK (year BETWEEN 2015 AND 2026),     -- memory: the year it happened
  tag_role        text        CHECK (tag_role IN ('bestie', 'study', 'mentor', 'chaos')),
  tagged_profile  bigint,                                        -- tag: the classmate
  title           text        CHECK (char_length(title) <= 120), -- song: "Song – Artist"
  body            text        NOT NULL DEFAULT '' CHECK (char_length(body) <= 600),
  hidden          boolean     NOT NULL DEFAULT false,
  reported        boolean     NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CHECK (kind <> 'tag' OR (tag_role IS NOT NULL AND tagged_profile IS NOT NULL)),
  CHECK (kind <> 'memory' OR year IS NOT NULL),
  CHECK (kind <> 'song' OR title IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS grad_posts_uid_idx ON public.grad_posts (uid, kind);
CREATE INDEX IF NOT EXISTS grad_posts_kind_idx ON public.grad_posts (kind, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS grad_posts_one_tag ON public.grad_posts (uid, tag_role) WHERE kind = 'tag';

ALTER TABLE public.grad_posts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.grad_posts FROM anon, authenticated;

CREATE OR REPLACE VIEW public.grad_posts_wall WITH (security_invoker = false) AS
  SELECT g.id, g.kind, g.year, g.tag_role, g.title, g.body, g.created_at,
         g.profile_id, CASE WHEN COALESCE(a.isanonymous, false) THEN 'A classmate' ELSE a.name END AS name,
         CASE WHEN COALESCE(a.isanonymous, false) THEN NULL ELSE a.photo_url END AS photo_url, a.course,
         g.tagged_profile, t.name AS tagged_name, t.photo_url AS tagged_photo
  FROM public.grad_posts g
  JOIN public.profiles a ON a.id = g.profile_id
  LEFT JOIN public.profiles t ON t.id = g.tagged_profile
  WHERE NOT g.hidden
    AND (g.kind <> 'tag' OR (t.id IS NOT NULL AND NOT COALESCE(t.isanonymous, false)))
    AND now() >= CASE g.kind
      WHEN 'memory' THEN timestamptz '2026-11-16 21:00:00+00'
      WHEN 'tag'    THEN timestamptz '2026-11-17 21:00:00+00'
      WHEN 'song'   THEN timestamptz '2026-11-18 21:00:00+00'
      WHEN 'joke'   THEN timestamptz '2026-11-18 21:00:00+00'
      ELSE               timestamptz '2026-11-19 21:00:00+00' END;
REVOKE ALL ON public.grad_posts_wall FROM anon, authenticated;
GRANT SELECT ON public.grad_posts_wall TO anon, authenticated;

CREATE OR REPLACE VIEW public.grad_posts_count WITH (security_invoker = false) AS
  SELECT kind, count(*)::int AS n FROM public.grad_posts WHERE NOT hidden GROUP BY kind;
REVOKE ALL ON public.grad_posts_count FROM anon, authenticated;
GRANT SELECT ON public.grad_posts_count TO anon, authenticated;

COMMIT;

-- =====================================================
--  GLUK YEARBOOK 2026 — STUDENT LEADERS (GLUKSA, class reps and others, past and present)
--
--    student_leaders         one row per person and office held, e.g. "President, GLUKSA, 2024/2025".
--                            The admin adds anyone (alumni with no yearbook profile too). A student may
--                            claim a role on their own profile: it waits (pending) until the admin approves.
--    student_leaders_public  the approved ones, with the linked profile's photo; what the website reads
--
--  An entry linked to a profile that is anonymous (or has gone anonymous) is never shown, so a leader's
--  name cannot unmask an anonymous profile. Nobody but the api function writes.
--
--  Order: 1) this file  2) redeploy supabase-api/index.ts  3) deploy the website
--         (the website works before 1 and 2; the leaders section just says it is coming)
--  Undo:  supabase/rollback/20261019000000_student_leaders_down.sql
--  Safe to run more than once.
-- =====================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.student_leaders (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id  bigint,                                   -- their yearbook profile, if they have one (no FK: archiving keeps the link)
  name        text        NOT NULL CHECK (char_length(name) BETWEEN 2 AND 120),
  org         text        NOT NULL CHECK (org IN ('gluksa', 'class', 'club', 'other')),
  title       text        NOT NULL CHECK (char_length(title) BETWEEN 2 AND 80),   -- Chairperson, President, Class representative …
  unit        text        CHECK (char_length(unit) <= 120),                       -- which class, club or campus
  term_from   integer     NOT NULL CHECK (term_from BETWEEN 1990 AND 2100),       -- 2024 and 2025 = the 2024/2025 term
  term_to     integer     CHECK (term_to IS NULL OR term_to BETWEEN term_from AND term_from + 8),
  current     boolean     NOT NULL DEFAULT false,       -- serving now
  honour      text        CHECK (char_length(honour) <= 60),                      -- e.g. President emeritus (the admin sets it)
  note        text        CHECK (char_length(note) <= 300),                       -- a line about their time in office
  photo_url   text,                                     -- the admin's upload, for someone with no profile photo
  status      text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'hidden')),
  claimed_by  text,                                     -- the Firebase login of the student who claimed it (NULL: the admin added it)
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by text                                      -- the admin's email: never public
);
CREATE INDEX IF NOT EXISTS student_leaders_status_idx  ON public.student_leaders (status, term_from DESC);
CREATE INDEX IF NOT EXISTS student_leaders_profile_idx ON public.student_leaders (profile_id);
CREATE INDEX IF NOT EXISTS student_leaders_claimed_idx ON public.student_leaders (claimed_by);
-- The same office and term only once per profile
CREATE UNIQUE INDEX IF NOT EXISTS student_leaders_once_idx
  ON public.student_leaders (profile_id, org, lower(title), term_from) WHERE profile_id IS NOT NULL;

ALTER TABLE public.student_leaders ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.student_leaders FROM anon, authenticated;

-- What the website reads: approved entries only, never who claimed or reviewed them.
-- It runs with its owner's rights (like profiles_public) so it can borrow the profile's photo, course and class.
CREATE OR REPLACE VIEW public.student_leaders_public
WITH (security_invoker = false) AS
SELECT
  l.id,
  CASE WHEN p.id IS NULL THEN NULL ELSE l.profile_id END        AS profile_id,
  l.name,
  l.org,
  l.title,
  l.unit,
  l.term_from,
  l.term_to,
  l.current,
  l.honour,
  l.note,
  COALESCE(NULLIF(l.photo_url, ''), p.photo_url)                 AS photo_url,
  p.course,
  p.classyear,
  l.created_at
FROM public.student_leaders l
LEFT JOIN public.profiles p ON p.id = l.profile_id
WHERE l.status = 'approved'
  AND NOT COALESCE(p.isanonymous, false);
REVOKE ALL ON public.student_leaders_public FROM anon, authenticated;
GRANT SELECT ON public.student_leaders_public TO anon, authenticated;
COMMENT ON VIEW public.student_leaders_public IS 'Approved student leaders for the website (Know your university, profile badges). Hides anyone whose linked profile is anonymous.';

COMMIT;

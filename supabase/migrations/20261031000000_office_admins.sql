--  GLUK YEARBOOK 2026 — SUPER ADMIN AND OFFICE ADMINS
--
--    office_admins   who runs which office's dashboard (office.html): 'dos' (Office of the Dean of Students)
--                    or 'alumni' (Directorate of External Affairs). Only the super admin (the adminEmail
--                    account) adds or removes them; the super admin sees every office.
--    office_audit    every full-list view and export an office makes, and every change to office_admins:
--                    who, which office, what, when. The super admin reads it in Developer > Audit.
--
--  Only the api function reads or writes them. Undo: supabase/rollback/20261031000000_office_admins_down.sql.
--  Safe to run more than once.
-- =====================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.office_admins (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text        NOT NULL CHECK (email = lower(email) AND email LIKE '%_@_%.__%'),
  office      text        NOT NULL CHECK (office IN ('dos', 'alumni')),
  granted_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (email, office)
);

CREATE TABLE IF NOT EXISTS public.office_audit (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text        NOT NULL,
  office      text,                                   -- empty for the super admin's own changes
  action      text        NOT NULL CHECK (char_length(action) BETWEEN 2 AND 60),
  detail      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS office_audit_at_idx ON public.office_audit (created_at DESC);

ALTER TABLE public.office_admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.office_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.office_admins, public.office_audit FROM anon, authenticated;

COMMIT;
